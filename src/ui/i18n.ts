/** Bot level 1–10 as "7 · Ուժեղ". */
export const levelName = (lang: Lang, level: number): string => `${level} · ${LEVEL_NAMES[lang][level - 1]}`;
export const isRed = (s: Strain): boolean => s === 'H' || s === 'D';
